//! The scales a `scale` line and `.scale(…)` know (#576): Strudel's, which
//! are tonal's (`tonaljs/tonal`, `packages/pitch-scale-type/data.ts`), each
//! with tonal's intervals beside its semitones so a test can hold them equal.
//!
//! Names are tonal's, made words a song can hold: spaces become `-`, `#n`
//! becomes `sharp-n` (a `#` starts a comment), `messiaen's mode #n` is
//! `messiaen-n`. The first name is the one a song prints; `pentatonic` and
//! `blues` keep the names they had here before, tonal's coming after.

/// A scale: its names, canonical first, tonal's intervals and the semitones
/// above the root.
pub(super) struct ModeDef {
    pub names: &'static [&'static str],
    /// Read only by the test that checks `steps` against it.
    #[cfg_attr(not(test), allow(dead_code))]
    pub tonal: &'static str,
    /// The error a name close to this one's gets.
    pub hint: &'static str,
    pub steps: &'static [u8],
}

